// Build a standalone file for design review. The source of truth stays in site/.
const { readFileSync, writeFileSync } = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => readFileSync(path.join(root, 'site', file), 'utf8');
let html = read('index.html');
const scripts = ['assets/js/config.js', 'assets/js/main.js'];
for (const script of scripts) {
  html = html.replace(`<script defer src="${script}"></script>`, '');
}
html = html.replace('<link rel="stylesheet" href="assets/css/style.css" />', () => `<style>\n${read('assets/css/style.css')}\n</style>`);
html = html.replace('href="assets/favicon.svg"', () => `href="data:image/svg+xml;base64,${Buffer.from(read('assets/favicon.svg')).toString('base64')}"`);
// Inline scripts must execute after the DOM, unlike the source's deferred files.
html = html.replace('</body>', () => scripts.map(script => `<script>\n${read(script).replace(/<\/script/gi, '<\\/script')}\n</script>`).join('\n') + '\n</body>');
writeFileSync(path.join(root, 'preview.html'), '<!-- Generated by npm run build:preview. Edit site/, not this file. -->\n' + html);
console.log('Built preview.html: no external assets required.');
